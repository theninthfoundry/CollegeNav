// Fallback coordinate generator for any intermediate stop
function getCoordinatesForStop(stopName: string, routeIndex: number, stopIndex: number, totalStops: number) {
  if (KNOWN_COORDINATES[stopName]) {
    return KNOWN_COORDINATES[stopName];
  }

  // Linear progression toward College Campus (17.205, 78.625)
  const progress = stopIndex / Math.max(1, totalStops - 1);
  const baseAngle = ((routeIndex * 13) % 360) * (Math.PI / 180);
  const startRadius = 0.28 + ((routeIndex % 5) * 0.04);
  const startLat = 17.205 + startRadius * Math.sin(baseAngle);
  const startLng = 78.625 + startRadius * Math.cos(baseAngle);

  const lat = Number((startLat + (17.205 - startLat) * progress).toFixed(4));
  const lng = Number((startLng + (78.625 - startLng) * progress).toFixed(4));

  return {
    lat,
    lng,
    landmark: `Stop near ${stopName}`,
  };
}


// 3. Compile Directional Route Stops with realistic offset minutes
export const FLEET_ROUTE_STOPS: any[] = [];

FLEET_ROUTES.forEach((route, rIdx) => {
  const raw = RAW_CAMPUS_BUS_ROUTES[rIdx];
  const totalStops = raw.stops.length;
  const avgHopMin = Math.round(55 / Math.max(1, totalStops - 1));

  // to_campus
  raw.stops.forEach((stopName, seq) => {
    const stopObj = uniqueStopsMap.get(stopName) || uniqueStopsMap.get("College Campus");
    FLEET_ROUTE_STOPS.push({
      route_id: route.id,
      direction: "to_campus" as const,
      seq: seq + 1,
      stop_id: stopObj.id,
      offset_min: seq * avgHopMin,
    });
  });

  // from_campus (reverse)
  const reversed = [...raw.stops].reverse();
  reversed.forEach((stopName, seq) => {
    const stopObj = uniqueStopsMap.get(stopName) || uniqueStopsMap.get("College Campus");
    FLEET_ROUTE_STOPS.push({
      route_id: route.id,
      direction: "from_campus" as const,
      seq: seq + 1,
      stop_id: stopObj.id,
      offset_min: seq * avgHopMin,
    });
  });
});

